// Stick-figure pictograms of gym movements, drawn on a 24 × 24 grid in the style of sports
// pictograms: a round head, thick round-capped limbs and the equipment. Each is a list of
// shapes: ["l", x1, y1, x2, y2, ...] a polyline, ["c", cx, cy, r] a filled circle,
// ["o", cx, cy, r] an outlined circle, ["p", d] a free path.

export type Shape = ["l", ...number[]] | ["c", number, number, number] | ["o", number, number, number] | ["p", string];

const head = (x: number, y: number): Shape => ["c", x, y, 2];
/** A barbell seen end-on: a plate. */
const plate = (x: number, y: number, r = 2.4): Shape => ["o", x, y, r];
/** A barbell seen from the front, with plates at both ends. */
const bar = (x1: number, x2: number, y: number): Shape[] => [
  ["l", x1, y, x2, y],
  ["l", x1 + 1, y - 2, x1 + 1, y + 2],
  ["l", x2 - 1, y - 2, x2 - 1, y + 2],
];
/** A dumbbell across the hand. */
const dumbbell = (x: number, y: number, vertical = false): Shape[] =>
  vertical ? [["l", x, y - 1.8, x, y + 1.8], ["l", x - 1, y - 1.8, x + 1, y - 1.8], ["l", x - 1, y + 1.8, x + 1, y + 1.8]] : [["l", x - 1.8, y, x + 1.8, y], ["l", x - 1.8, y - 1, x - 1.8, y + 1], ["l", x + 1.8, y - 1, x + 1.8, y + 1]];
