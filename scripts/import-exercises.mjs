// Imports free-exercise-db (public domain, The Unlicense; packaged in "react-muscle-map")
// into src/data/openExercises.ts (rows) and public/data/exercise-instructions.json (steps).
// Exercises whose names already exist in the app are skipped. Run: npm run data:exercises
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = path.dirname(require.resolve("react-muscle-map/package.json"));
const all = JSON.parse(fs.readFileSync(path.join(pkg, "datasets/exercises.json"), "utf8"));

// Names already in the app (curated lists), ignoring case and punctuation ("Muscle-up" = "Muscle Up").
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const existing = new Set(
  ["exercises.ts", "moreExercises.ts", "moreExercises2.ts"]
    .map((f) => path.resolve("src/data", f))
    .filter((f) => fs.existsSync(f))
    .flatMap((f) => [...fs.readFileSync(f, "utf8").matchAll(/^\s*\["([^"]+)"/gm)].map((m) => norm(m[1]))),
);

const GROUP = {
  chest: "Chest", lats: "Back", "middle back": "Back", "lower back": "Back", traps: "Back", neck: "Shoulders",
  shoulders: "Shoulders", biceps: "Arms", triceps: "Arms", forearms: "Arms", quadriceps: "Legs", hamstrings: "Legs",
  glutes: "Legs", calves: "Legs", adductors: "Legs", abductors: "Legs", abdominals: "Core",
};
const EQUIPMENT = {
  barbell: "Barbell", dumbbell: "Dumbbell", cable: "Cable", machine: "Machine", "body only": "Bodyweight",
  kettlebells: "Kettlebell", bands: "Resistance band", "e-z curl bar": "EZ bar",
};
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const firstSentence = (steps) => {
  const s = (steps?.[0] ?? "").replace(/\s+/g, " ").trim();
  if (s.length <= 110) return s;
  const cut = s.slice(0, 107);
  return `${cut.slice(0, cut.lastIndexOf(" "))}…`;
};

const strength = [];
const cardio = [];
const instructions = {};
const seen = new Set(existing);
for (const e of all) {
  const key = norm(e.name);
  if (seen.has(key)) continue;
  seen.add(key);
  instructions[e.name] = e.instructions ?? [];
  if (e.category === "cardio") {
    cardio.push([e.name, "Gym Cardio", 7.0]);
    continue;
  }
  const muscles = [...e.primaryMuscles, ...e.secondaryMuscles].map(cap);
  const group =
    e.category === "plyometrics" || e.category === "strongman" || e.category === "olympic weightlifting"
      ? "Full Body"
      : GROUP[e.primaryMuscles[0]] ?? "Full Body";
  // MET: stretching 2.3, isolation 3.5, compound 5, powerlifting 6, Olympic/strongman 6–8, plyometrics 8.
  const met =
    e.category === "stretching" ? 2.3
    : e.category === "plyometrics" ? 8
    : e.category === "strongman" ? 7.5
    : e.category === "olympic weightlifting" ? 6
    : e.category === "powerlifting" ? 6
    : e.mechanic === "compound" ? 5
    : 3.5;
  strength.push([e.name, group, EQUIPMENT[e.equipment] ?? (e.equipment ? "Equipment" : "Bodyweight"), met, muscles.join(", ") || cap(group), firstSentence(e.instructions)]);
}

const header = `// GENERATED by scripts/import-exercises.mjs from free-exercise-db (public domain, The Unlicense).
// Do not edit by hand. Rows use the same format as exercises.ts.
import type { CardioRow, StrengthRow } from "./exercises";
`;
fs.writeFileSync(
  "src/data/openExercises.ts",
  `${header}
export const OPEN_CARDIO: CardioRow[] = ${JSON.stringify(cardio, null, 0).replace(/\],\[/g, "],\n  [")};

export const OPEN_STRENGTH: StrengthRow[] = ${JSON.stringify(strength, null, 0).replace(/\],\[/g, "],\n  [")};
`,
);
fs.mkdirSync("public/data", { recursive: true });
fs.writeFileSync("public/data/exercise-instructions.json", JSON.stringify(instructions));
console.log(`${strength.length} strength + ${cardio.length} cardio imported (${all.length - strength.length - cardio.length} skipped as duplicates)`);
